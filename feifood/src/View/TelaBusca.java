    private void btnAdicionarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAdicionarActionPerformed
        int linha = tabelaAlimentos.getSelectedRow();
    if (linha == -1) {
        JOptionPane.showMessageDialog(this, "Selecione um item primeiro!");
        return;
    }

    String nome = tabelaAlimentos.getValueAt(linha, 0).toString();
    Alimento alimento = ControllerAlimento.buscarPorNome(nome);

    if (alimento != null) {
        ControllerPedido.adicionarAoCarrinho(alimento);
        JOptionPane.showMessageDialog(this, nome + " adicionado ao carrinho!");
    }
    }//GEN-LAST:event_btnAdicionarActionPerformed


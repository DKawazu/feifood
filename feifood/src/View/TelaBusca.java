     private void listarAlimentos() {
        String termo = txtBuscar.getText().trim();
        DefaultTableModel modelo = new DefaultTableModel(
            new Object[]{"Nome", "Tipo", "Preço (R$)"}, 0
        );

        try {
            List<Alimento> lista;

            if (termo.isEmpty()) {
                lista = ControllerAlimento.listarTodos();
            } else {
                lista = ControllerAlimento.listarTodos(termo);
            }

            for (Alimento a : lista) {
                String tipo = (a instanceof Bebida) ? "Bebida" : "Comida";
                double precoFinal;

                if (a instanceof Bebida) {
                    Bebida b = (Bebida) a;
                    precoFinal = a.getPreco() + b.calcularImposto(); // preço + imposto
                } else {
                    precoFinal = a.getPreco();
                }

                modelo.addRow(new Object[]{
                    a.getNome(),
                    tipo,
                    String.format("R$ %.2f", precoFinal)
                });
            }

            tabelaAlimentos.setModel(modelo);

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro ao listar alimentos: " + e.getMessage());
        }
    }

    private void configurarAtualizacaoAutomatica() {
        txtBuscar.getDocument().addDocumentListener(new DocumentListener() {
            @Override
            public void insertUpdate(DocumentEvent e) {
                listarAlimentos();
            }
            @Override
            public void removeUpdate(DocumentEvent e) {
                listarAlimentos();
            }
            @Override
            public void changedUpdate(DocumentEvent e) {
                listarAlimentos();
            }
        });
    }



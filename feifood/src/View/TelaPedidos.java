    private void btnAvaliarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAvaliarActionPerformed
        int linha = tabelaPedidos.getSelectedRow();
        if (linha == -1) {
            JOptionPane.showMessageDialog(this, "Selecione um pedido para avaliar!");
            return;
        }

        // usa o cache para garantir que a linha corresponde ao pedido certo
        int pedidoId = pedidosCache.get(linha).getId();

        String notaStr = JOptionPane.showInputDialog(this, "Dê uma nota de 0 a 5 estrelas:");
        if (notaStr == null) return;

        try {
            int nota = Integer.parseInt(notaStr.trim());
            if (nota < 0 || nota > 5) {
                JOptionPane.showMessageDialog(this, "A nota deve ser entre 0 e 5!");
                return;
            }
            ControllerPedido.avaliarPedido(pedidoId, nota);
            carregarPedidos(); // recarrega já com as estrelas atualizadas
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Digite um número válido!");
        }
        
        
    }//GEN-LAST:event_btnAvaliarActionPerformed



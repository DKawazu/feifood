    private void carregarPedidos() {
        DefaultTableModel modelo = new DefaultTableModel(
            new Object[]{"Data do Pedido", "Itens", "Avaliação"}, 0
        ) {
            @Override public boolean isCellEditable(int r, int c) { return false; }
        };

        pedidosCache = ControllerPedido.listarPedidos();

        for (Pedido p : pedidosCache) {
            String dataFmt = p.getData()
                .toInstant()
                .atZone(ZoneId.systemDefault())
                .toLocalDateTime()
                .format(FMT);

            String itensConcatenados = String.join(", ", p.getItensNomes());
            String estrelas = gerarEstrelas(p.getAvaliacao());
            modelo.addRow(new Object[]{ dataFmt, itensConcatenados, estrelas });
        }

        tabelaPedidos.setModel(modelo);
        ajustarLarguras(); // garante largura após setModel
    }
    
    private void ajustarLarguras() {

    // 0 = Data, 1 = Itens, 2 = Avaliação
    var cols = tabelaPedidos.getColumnModel();
    cols.getColumn(0).setPreferredWidth(160);  // Data
    cols.getColumn(1).setPreferredWidth(520);  // Itens (maior espaço)
    cols.getColumn(2).setPreferredWidth(90);   // Estrelas (pequena)

    // Centraliza as estrelinhas (opcional)
    javax.swing.table.DefaultTableCellRenderer center = new javax.swing.table.DefaultTableCellRenderer();
    center.setHorizontalAlignment(javax.swing.SwingConstants.CENTER);
    cols.getColumn(2).setCellRenderer(center);
}


    private String gerarEstrelas(int nota) {
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < 5; i++) {
            sb.append(i < nota ? "★" : "☆");
        }
        return sb.toString();
    }



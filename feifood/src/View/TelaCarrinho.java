    private void removerItem() {
        int linha = tabelaCarrinho.getSelectedRow();
        if (linha == -1) {
            JOptionPane.showMessageDialog(this, "Selecione um item para remover!");
            return;
        }

        String nome = tabelaCarrinho.getValueAt(linha, 0).toString();
        ControllerPedido.removerDoCarrinho(
            ControllerAlimento.buscarPorNome(nome)
        );
        atualizarTabela();

        if (ControllerPedido.getCarrinho().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Carrinho vazio!");
        }
    }

    private void finalizarPedido() {
        int usuarioId = 1; // substituir depois pelo ID real
        if (ControllerPedido.finalizarPedido(usuarioId)) {
            JOptionPane.showMessageDialog(this, "Pedido realizado com sucesso!");
            ControllerPedido.limparCarrinho();
            atualizarTabela();
        } else {
            JOptionPane.showMessageDialog(this, "Carrinho vazio!");
        }
    }



    private void atualizarTabela() {
        DefaultTableModel modelo = new DefaultTableModel(
            new Object[]{"Nome", "Qtd", "Preço (R$)"}, 0
        );
        double total = 0.0;

        for (ItemPedido item : ControllerPedido.getCarrinho()) {
            double preco = item.getAlimento().getPreco();

        if (item.getAlimento() instanceof Model.Bebida bebida && bebida.isAlcoolica()) {
            preco += bebida.calcularImposto();
        }

            double subtotal = preco * item.getQuantidade();
            total += subtotal;

            modelo.addRow(new Object[]{
                item.getAlimento().getNome(),
                item.getQuantidade(),
                String.format("R$ %.2f", subtotal)
            });
        }

        tabelaCarrinho.setModel(modelo);
        lblTotal.setText(String.format("Total: R$ %.2f", total));
    }

